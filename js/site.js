const TOKEN_KEY = "wtc_token";
const LANG_KEY = "wtc_lang";
const THEME_KEY = "wtc_theme";
const MARK = "/img/badge.png?v=49";
const WORD = (t) => `/img/wordmark-${t}.png?v=49`;

function lang() {
  return localStorage.getItem(LANG_KEY) === "en" ? "en" : "pt";
}

function theme() {
  return localStorage.getItem(THEME_KEY) === "light" ? "light" : "dark";
}

function applyTheme() {
  const t = theme();
  document.documentElement.setAttribute("data-theme", t);
  const word = WORD(t);
  document.querySelectorAll("[data-wordmark]").forEach((el) => { el.src = word; });
  document.querySelectorAll("[data-logo]").forEach((el) => {
    if (el.classList.contains("is-player")) return;
    el.src = MARK;
  });
  document.querySelectorAll("[data-icon]").forEach((el) => { el.src = MARK; });
}

function t(key) {
  return (I18N[lang()] && I18N[lang()][key]) || I18N.pt[key] || key;
}

function applyI18n() {
  document.documentElement.lang = lang() === "en" ? "en" : "pt-BR";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-lang]").forEach((el) => {
    el.textContent = t("lang.switch");
  });
  document.querySelectorAll("[data-theme-btn]").forEach((el) => {
    el.textContent = t(theme() === "light" ? "theme.dark" : "theme.light");
  });
  const toggle = document.querySelector("[data-menu]");
  if (toggle) {
    const open = document.querySelector(".header")?.classList.contains("is-open");
    toggle.setAttribute("aria-label", t(open ? "nav.close" : "nav.menu"));
  }
  document.dispatchEvent(new Event("wtc:lang"));
}

function pageId() {
  const path = location.pathname.replace(/\/+$/, "") || "/";
  if (path === "/" || path === "/index") return "home";
  if (path.startsWith("/players/") || path.startsWith("/jogador/")) return "player";
  if (path.startsWith("/sobre") || path.startsWith("/about")) return "about";
  if (path.startsWith("/login") || path.startsWith("/admin")) return "login";
  return path.replace(/^\//, "");
}

function navItems(here) {
  return [
    ["/", here === "home", "nav.home"],
    ["/players", here === "players" || here === "player", "nav.players"],
    ["/stats", here === "stats", "nav.stats"],
    ["/clips", here === "clips", "nav.clips"],
    ["/sobre", here === "about", "nav.about"]
  ].map(([href, on, key]) =>
    `<a href="${href}" class="${on ? "is-on" : ""}" data-i18n="${key}"></a>`
  ).join("");
}

function setMenu(open) {
  const header = document.getElementById("header");
  const toggle = document.querySelector("[data-menu]");
  const sheet = document.getElementById("nav-sheet");
  if (!header) return;
  header.classList.toggle("is-open", open);
  document.body.classList.toggle("nav-open", open);
  if (sheet) {
    sheet.classList.toggle("is-open", open);
    sheet.setAttribute("aria-hidden", open ? "false" : "true");
  }
  if (toggle) {
    toggle.setAttribute("aria-expanded", open ? "true" : "false");
    toggle.setAttribute("aria-label", t(open ? "nav.close" : "nav.menu"));
  }
}

