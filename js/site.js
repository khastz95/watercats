let motionIo;
function motion() {
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const sel = ".hero, .section, .facts, .pulse, .star-stage, .table-wrap, .clip-filters, .login-stage, .profile-hero, .profile, .hot-grid, .card, .spot, .house-strip, .players, .match-ribbon, .info-strip, .about-hero, .clip-reel, .story-grid, .place-box, .season-board, .season-sheet, .season-hot";
  if (reduce) {
    document.querySelectorAll(sel).forEach((el) => el.classList.add("is-in"));
    runCounts(document);
    return;
  }
  if (!motionIo) {
    motionIo = new IntersectionObserver((entries) => {
      entries.forEach((e) => {
        if (!e.isIntersecting) return;
        e.target.classList.add("is-in");
        runCounts(e.target);
        motionIo.unobserve(e.target);
      });
    }, { threshold: 0.08, rootMargin: "0px 0px -6% 0px" });
  }
  document.querySelectorAll(sel).forEach((el, i) => {
    if (el.classList.contains("is-in")) return;
    el.classList.add("reveal");
    el.style.setProperty("--d", `${(i % 8) * 0.06}s`);
    motionIo.observe(el);
  });
}

function fmtDuration(n) {
  const s = Math.round(Number(n));
  if (!Number.isFinite(s) || s < 0) return "";
  const m = Math.floor(s / 60);
  const r = s % 60;
  return m ? `${m}:${String(r).padStart(2, "0")}` : `${s}s`;
}

function clipReel(clips) {
  const rows = (clips || []).slice(0, 12);
  if (!rows.length) return "";
  const cards = rows.map((c) => clipCard(c)).join("");
  return `<div class="clip-reel" data-reel>
    <div class="reel-track">${cards}${cards}</div>
  </div>`;
}

function clipPager(clips, shown) {
  const rows = clips || [];
  const size = Math.max(shown, 0);
  const slice = rows.slice(0, size);
  const more = size < rows.length
    ? `<div class="clip-more"><button type="button" class="btn" data-clip-more>${t("clips.more")}</button></div>`
    : "";
  if (!slice.length) return emptyBox("empty.clips");
  return slice.map((c, i) => clipCard(c, { featured: i === 0 })).join("") + more;
}

function clipCard(c, options = {}) {
  const featured = Boolean(options && options.featured);
  const meta = [c.playerName, c.map, c.weapon].filter(Boolean).join(" · ");
  const time = c.duration != null ? fmtDuration(c.duration) : "";
  const poster = c.thumb
    ? `<button type="button" class="clip-play" data-play-clip="${escapeAttr(c.embed)}" data-play-title="${escapeAttr(c.title)}" aria-label="${escapeAttr(t("clips.play") + ": " + c.title)}">
         <img src="${escapeAttr(c.thumb)}" alt="" loading="lazy">
         <span class="clip-play-icon" aria-hidden="true"></span>
         ${time ? `<span class="clip-time">${escapeHtml(time)}</span>` : ""}
       </button>`
    : `<iframe src="${escapeAttr(c.embed)}" allow="autoplay; fullscreen; picture-in-picture" allowfullscreen loading="lazy" title="${escapeAttr(c.title)}"></iframe>`;
  return `<article class="card clip${featured ? " is-featured" : ""}">
    ${poster}
    <div class="clip-body">
      <h3>${escapeHtml(c.title)}</h3>
      <p class="meta">${escapeHtml(meta)}${c.views != null ? ` · ${c.views}` : ""}</p>
    </div>
  </article>`;
}

