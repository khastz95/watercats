function houseCards(players, clips) {
  const all = (players || []).map(stats);
  const ratings = all.map((s) => s.rating).filter((v) => v != null);
  const topRating = ratings.length ? Math.max(...ratings) : null;
  const maps = all.reduce((n, s) => n + (s.matches || 0), 0);
  const winrates = all.map((s) => s.winrate).filter((v) => v != null);
  const avgWin = winrates.length ? winrates.reduce((a, b) => a + b, 0) / winrates.length : null;
  const premiers = all.map((s) => s.premier).filter((v) => v != null);
  const topPremier = premiers.length ? Math.max(...premiers) : null;
  return [
    countBox(players.length, t("stat.players"), players.length),
    countBox(dash(topRating, 2), t("stat.rating"), topRating, 2),
    countBox(dash(maps), t("stat.maps"), maps),
    countBox((clips || []).length, t("stat.clips"), (clips || []).length),
    countBox(avgWin == null ? "—" : pct(avgWin), t("stat.winrate"), avgWin == null ? null : avgWin * 100, 1, "%"),
    countBox(dash(topPremier), t("stat.premier"), topPremier)
  ].join("");
}

let motionIo;
function motion() {
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const sel = ".hero, .section, .facts, .pulse, .star-stage, .table-wrap, .clip-filters, .login-stage, .profile-hero, .profile, .hot-grid, .card, .spot, .house-strip, .players, .match-ribbon, .info-strip, .about-hero";
  if (reduce) {
    document.querySelectorAll(sel).forEach((el) => el.classList.add("is-in"));
    runCounts(document);
    return;
  }
  if (!motionIo) {
    motionIo = new IntersectionObserver((entries) => {
      entries.forEach((e) => {
        if (!e.isIntersecting) return;
        e.target.classList.add("is-in");
        runCounts(e.target);
        motionIo.unobserve(e.target);
      });
    }, { threshold: 0.08, rootMargin: "0px 0px -6% 0px" });
  }
  document.querySelectorAll(sel).forEach((el, i) => {
    if (el.classList.contains("is-in")) return;
    el.classList.add("reveal");
    el.style.setProperty("--d", `${(i % 8) * 0.06}s`);
    motionIo.observe(el);
  });
}

function fmtDuration(n) {
  const s = Math.round(Number(n));
  if (!Number.isFinite(s) || s < 0) return "";
  const m = Math.floor(s / 60);
  const r = s % 60;
  return m ? `${m}:${String(r).padStart(2, "0")}` : `${s}s`;
}

